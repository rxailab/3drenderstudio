// Run: node validation/frontend-material-agent-tests.js
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const html=fs.readFileSync('static/index.html','utf8'),source=fs.readFileSync('static/app.js','utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(match=>match[1]);
assert.equal(ids.length,new Set(ids).size,'All inspector controls have unique IDs');
const elements=Object.fromEntries(ids.map(id=>[id,{value:'',disabled:false,hidden:false,checked:false,textContent:'',innerHTML:'',setAttribute(name,value){this[name]=value;}}]));
let calls=[],resolveRequest;
const context=vm.createContext({console,URL,document:{getElementById:id=>elements[id]},FormData:class{},clearTimeout(){},setTimeout(){},fetch:async(path,options={})=>{
  calls.push({path,body:options.body?JSON.parse(options.body):null});
  return {ok:true,json:async()=>await new Promise(resolve=>resolveRequest=resolve)};
}});
vm.runInContext(source.replace(/start\(\)\.catch\(e=>toast\(e.message,true\)\);\s*$/,''),context);
const run=code=>vm.runInContext(code,context),plain=value=>JSON.parse(JSON.stringify(value));
run(`current={id:'p',version:2,jobs:[],plan:{object_material_overrides:[]}};currentOutput={job_id:'j',shot_id:'hero',version:2,quality:'preview'};feedbackMode=true;
feedbackSource={projectId:'p',key:sceneOutputKey(currentOutput),snapshot:feedbackSnapshot()};feedbackPoints=[{id:'point',x:.4,y:.5,hit:true,object_name:'Body',material_name:'Surface'}];`);
run('renderMaterialAgent();');
assert.equal(elements.materialAgentSubmit.disabled,false);
assert.equal(elements.materialAgentColor.checked,false,'Imported base color requires explicit opt-in');
assert(elements.materialAgentHint.textContent.includes('1 个部件材质'));
run("setInspectorTab('material');");
assert.equal(elements.inspectorReview.hidden,true);
assert.equal(elements.inspectorMaterial.hidden,false);
run("setInspectorTab('review');");
assert.equal(elements.inspectorReview.hidden,false,'Diagnostic tab remains available without approval controls');
assert(!ids.includes('reviewApplyDock'),'Automatic diagnostics require no approval dock');
assert(html.includes('<details class="review-evidence">'),'Detailed evidence is closed initially');
assert(!html.includes('<details class="review-evidence" open'));
run('dirty=true;renderMaterialAgent();');assert.equal(elements.materialAgentSubmit.disabled,true);
run('dirty=false;current.version=3;renderMaterialAgent();');assert.equal(elements.materialAgentSubmit.disabled,true);
run('current.version=2;feedbackPoints[0].hit=false;renderMaterialAgent();');assert.equal(elements.materialAgentSubmit.disabled,true);
run('feedbackPoints[0].hit=true;renderMaterialAgent();');
elements.materialAgentPrompt.value='细腻拉丝金属，保留原色';
async function main(){
  const request=run('submitMaterialAgent({preventDefault(){}})');
  assert.equal(elements.materialAgentSubmit.disabled,true,'Submission disables duplicate clicks');
  await run('submitMaterialAgent({preventDefault(){}})');
  assert.equal(calls.length,1);
  assert.deepEqual(calls[0],{path:'/api/projects/p/material-agent/tasks',body:{output_id:'j',shot_id:'hero',quality:'preview',version:2,points:[{id:'point',x:.4,y:.5}],prompt:'细腻拉丝金属，保留原色',use_base_color:false}});
  resolveRequest({id:'task',status:'running',stage:'下载法线贴图',prompt:'细腻拉丝金属',use_base_color:false,selection:{name:'Brushed <metal>',url:'https://polyhaven.com/a/metal',license:'CC0',license_url:'https://creativecommons.org/publicdomain/zero/1.0/'}});
  await request;
  assert.equal(elements.materialAgentSubmit.disabled,true);
  assert(elements.materialAgentTasks.innerHTML.includes('下载法线贴图'));
  assert(elements.materialAgentTasks.innerHTML.includes('Brushed &lt;metal&gt;'));
  assert(elements.materialAgentTasks.innerHTML.includes('href="https://polyhaven.com/a/metal"'));
  assert(!elements.materialAgentTasks.innerHTML.includes('预览已完成'));
  assert(elements.materialAgentTasks.innerHTML.includes('data-cancel-material="task"'));
  assert.equal(run('current.version'),2,'Only backend applies a plan; submit invents no render or result');
  run("storeMaterialTask('p',{id:'task',status:'rendering',stage:'Cycles 真实渲染中'});renderMaterialAgent();");
  assert(elements.materialAgentTasks.innerHTML.includes('真实预览中'));
  assert(!elements.materialAgentTasks.innerHTML.includes('预览已完成'));
  run("storeMaterialTask('p',{id:'task',status:'completed',stage:'预览已完成',applied_version:3});renderMaterialAgent();");
  assert(elements.materialAgentTasks.innerHTML.includes('预览已完成'));
  assert.equal(elements.materialAgentSubmit.disabled,false);
  run("storeMaterialTask('p',{id:'evil',status:'failed',stage:'失败',error:'<bad>',selection:{name:'test',url:'javascript:alert(1)',license_url:'https://evil.example/license'}});renderMaterialAgent();");
  assert(!elements.materialAgentTasks.innerHTML.includes('javascript:'));
  assert(!elements.materialAgentTasks.innerHTML.includes('https://evil.example'));
  assert(elements.materialAgentTasks.innerHTML.includes('&lt;bad&gt;'));
  assert(elements.materialAgentTasks.innerHTML.includes('之前的材质任务（1）'));
  assert(/data-material-detail="history"[^>]*>/.test(elements.materialAgentTasks.innerHTML));
  assert(!/data-material-detail="history"[^>]*open/.test(elements.materialAgentTasks.innerHTML),'Older tasks start collapsed');
  run("materialAgentDisclosures.set('p:history',true);storeMaterialTask('p',{id:'evil',status:'failed',stage:'失败，已保留下载记录'});renderMaterialAgent();");
  assert(/data-material-detail="history"[^>]*open/.test(elements.materialAgentTasks.innerHTML),'Task polling preserves expanded history');
  run("storeMaterialTask('p',{id:'active',status:'running',stage:'正在下载'});storeMaterialTask('p',{id:'newest',status:'failed',stage:'提交失败'});renderMaterialAgent();");
  assert(elements.materialAgentTasks.innerHTML.indexOf('正在下载')<elements.materialAgentTasks.innerHTML.indexOf('之前的材质任务'),'An active task stays visible even if a newer terminal record exists');
  run("current={...current,id:'different'};renderMaterialAgent();");
  assert.equal(elements.materialAgentTasks.innerHTML,'','Task history stays scoped to its project');
  console.log('Material agent UI passed: snapshot/selected parts, color consent, stale guards, double submit, actual task stages, source link safety, project scoping, preview inspector tabs.');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
