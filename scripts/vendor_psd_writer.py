"""Vendor the Photoshop file writer used by the text layer's PSD export.

ag-psd (MIT, https://github.com/Agamnentzar/ag-psd) writes PSD files in the
browser: pixel layers, editable text layers and vector shape layers. Its
browser bundle carries two small dependencies, pako (MIT and zlib licences)
and base64-js (MIT); their licences are copied beside it.

Every tarball is checked against the integrity hash the npm registry
publishes. The result is written to static/vendor/ag-psd/ together with a
VENDORED.json listing versions and hashes. Run it again with other versions to
update:

    python scripts/vendor_psd_writer.py
"""
import base64
import hashlib
import io
import json
import sys
import tarfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'static' / 'vendor' / 'ag-psd'
REGISTRY = 'https://registry.npmjs.org/'
WRITER = ('ag-psd', '34.2.0')
# The dependencies the bundle includes, at the versions ag-psd pins.
BUNDLED = (('pako', '2.1.0'), ('base64-js', '1.5.1'))


def fetch(url):
    request = urllib.request.Request(url, headers={'User-Agent': 'studio-vendor-psd'})
    with urllib.request.urlopen(request, timeout=120) as response:
        return response.read()


def package(name, version):
    """(metadata, verified tarball) of one npm package version."""
    meta = json.loads(fetch(REGISTRY + name + '/' + version))
    tarball = fetch(meta['dist']['tarball'])
    algorithm, expected = meta['dist']['integrity'].split('-', 1)
    if algorithm != 'sha512' or base64.b64encode(hashlib.sha512(tarball).digest()).decode() != expected:
        raise SystemExit('%s %s: tarball does not match the registry integrity hash' % (name, version))
    return meta, tarball


def member(tarball, path):
    with tarfile.open(fileobj=io.BytesIO(tarball), mode='r:gz') as archive:
        return archive.extractfile('package/' + path).read()


def main():
    TARGET.mkdir(parents=True, exist_ok=True)
    name, version = WRITER
    meta, tarball = package(name, version)
    dependencies = meta.get('dependencies') or {}
    if dependencies != dict(BUNDLED):
        raise SystemExit('%s %s bundles %s, not %s: update BUNDLED and the licences' % (name, version, dependencies, dict(BUNDLED)))
    bundle = member(tarball, 'dist/bundle.js')
    (TARGET / 'ag-psd.js').write_bytes(bundle)
    (TARGET / 'LICENSE-ag-psd.txt').write_bytes(member(tarball, 'LICENSE'))
    record = {'purpose': 'Writes the Photoshop (PSD) export of the text layer in the browser (static/layer.js). Generated by scripts/vendor_psd_writer.py.',
              'packages': [{'package': name, 'version': version, 'license': meta.get('license'), 'tarball': meta['dist']['tarball'],
                            'integrity': meta['dist']['integrity'], 'file': 'ag-psd.js', 'source': 'dist/bundle.js',
                            'sha256': hashlib.sha256(bundle).hexdigest()}]}
    for dependency, pinned in BUNDLED:
        dep_meta, dep_tarball = package(dependency, pinned)
        (TARGET / ('LICENSE-%s.txt' % dependency)).write_bytes(member(dep_tarball, 'LICENSE'))
        record['packages'].append({'package': dependency, 'version': pinned, 'license': dep_meta.get('license'), 'tarball': dep_meta['dist']['tarball'],
                                   'integrity': dep_meta['dist']['integrity'], 'bundled_in': 'ag-psd.js'})
    (TARGET / 'VENDORED.json').write_text(json.dumps(record, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print('ag-psd %s: %d bytes, sha256 %s' % (version, len(bundle), record['packages'][0]['sha256']))


if __name__ == '__main__':
    sys.exit(main())
